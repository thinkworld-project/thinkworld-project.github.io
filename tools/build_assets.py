def trim_letterbox(im, tol=12):
    """Remove the flat padding bands that the closed-loop RGB tiles carry above and below the frame."""
    a = np.asarray(im.convert('RGB')).astype(int)
    bg = a[0, 0]
    rows = np.where((np.abs(a - bg).sum(-1) > tol).any(1))[0]
    cols = np.where((np.abs(a - bg).sum(-1) > tol).any(0))[0]
    if len(rows) == 0:
        return im
    return im.crop((cols[0], rows[0], cols[-1] + 1, rows[-1] + 1))


def build_closed_loop(a):
    base = os.path.join(a.video_dir, 'closed_loop_future_pca',
                        '20260920_stage3_2k_long_rollout_post_interaction_suite',
                        'visualizations_rowwise_actual_only_pca', 'simplerenv')
    out = mkdir(os.path.join(IMG, 'closed_loop'))
    data = []
    for key, title, robot in CL_TASKS:
        d = os.path.join(base, key, 'tiles')
        steps = []
        for p in sorted(glob.glob(os.path.join(d, 'predicted_pca', 'query_*_target_*.png'))):
            q, t = map(int, re.findall(r'query_(\d+)_target_(\d+)', p)[0])
            obs = os.path.join(d, 'actual_rgb', f'observation_{t:03d}.png')
            cur = os.path.join(d, 'actual_rgb', f'observation_{q:03d}.png')
            tgt = os.path.join(d, 'target_pca', os.path.basename(p))
            if not (os.path.exists(obs) and os.path.exists(cur)):
                continue
            n = len(steps)
            save_webp(trim_letterbox(Image.open(cur)), os.path.join(out, key, f'{n:02d}_cur.webp'), width=320, quality=82)
            save_webp(trim_letterbox(Image.open(obs)), os.path.join(out, key, f'{n:02d}_obs.webp'), width=320, quality=82)
            save_webp(Image.open(p).convert('RGB').resize((320, 320), Image.NEAREST),
                      os.path.join(out, key, f'{n:02d}_pred.webp'), quality=90)
            if os.path.exists(tgt):
                save_webp(Image.open(tgt).convert('RGB').resize((320, 320), Image.NEAREST),
                          os.path.join(out, key, f'{n:02d}_tgt.webp'), quality=90)
            steps.append({'query': q, 'target': t})
        data.append({'key': key, 'title': title, 'robot': robot, 'steps': steps})
        print(f'  closed-loop {key}: {len(steps)} steps')
    write_js('data_closed_loop.js', 'CLOSED_LOOP', data)


