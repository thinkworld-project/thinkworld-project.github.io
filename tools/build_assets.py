def build_future_pred(a):
    out = os.path.join(IMG, 'future_pred')
    shutil.rmtree(out, ignore_errors=True)  # drop panels of samples no longer shown
    mkdir(out)
    # Local copies of the RGB frames, used only to verify that each PDF row is the expected sample.
    local = {}
    for d in glob.glob(os.path.join(a.fig_dir, 'selected_*_rowwise_actual_only_pca_v4', 'sample_*')):
        p = os.path.join(d, 'individual', '01_current_observation_rgb.png')
        if os.path.exists(p):
            local.setdefault(os.path.basename(d), p)
    thumb = lambda im: np.asarray(im.convert('RGB').resize((24, 24), Image.BOX), dtype=np.float32)
    samples = []
    with tempfile.TemporaryDirectory() as td:
        imgs = {}
        for first, (p0, p1) in FP_PAGES.items():
            stem = os.path.join(td, f'p{first}')
            sh(['pdfimages', '-png', '-f', str(p0), '-l', str(p1), a.paper, stem])
            imgs[first] = sorted(glob.glob(stem + '-*.png'))
        for sid, (first, idx) in FP_SOURCES:
            files = [imgs[first][i] for i in idx]
            if sid in local:  # sanity check: PDF current-obs panel == local current-obs frame
                err = float(((thumb(Image.open(files[0])) - thumb(Image.open(local[sid]))) ** 2).mean())
                if err > 5:
                    raise RuntimeError(f'{sid}: paper panel does not match local frame (err={err:.1f}); '
                                       'did the figure layout or page numbers change?')
            for (key, _), f in zip(FP_PANELS, files):
                save_webp(Image.open(f).convert('RGB'), os.path.join(out, sid, key + '.webp'), quality=90)
            ds = re.sub(r'^sample_\d+_', '', sid)
            samples.append({'id': sid, 'dataset': DATASET_NAMES.get(ds, ds),
                            'figure': 'Fig. 5' if first == 8 else 'Fig. 11'})
    write_js('data_future_pred.js', 'FUTURE_PRED', {
        'panels': [{'key': k, 'label': l} for k, l in FP_PANELS], 'samples': samples})
    print(f'  future-pred samples: {len(samples)}')


