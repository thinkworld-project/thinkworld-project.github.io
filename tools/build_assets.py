# --------------------------------------------------------------------------- helpers
def sh(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(' '.join(cmd) + '\n' + r.stderr[-2000:])
    return r.stdout


def mkdir(p):
    os.makedirs(p, exist_ok=True)
    return p


def save_webp(im, dst, width=None, quality=84):
    im = im.convert('RGB') if im.mode not in ('RGB', 'RGBA') else im
    if width and im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    mkdir(os.path.dirname(dst))
    im.save(dst, 'WEBP', quality=quality, method=6)


def pdf_to_image(pdf, width):
    with tempfile.TemporaryDirectory() as td:
        stem = os.path.join(td, 'p')
        sh(['pdftocairo', '-png', '-singlefile', '-scale-to-x', str(width), '-scale-to-y', '-1', pdf, stem])
        return Image.open(stem + '.png').copy()


def encode(src, dst, width, crf=28, extra_vf=None, max_seconds=None):
    """H.264, no audio, faststart; plus a WebP poster from the first frame."""
    mkdir(os.path.dirname(dst))
    vf = f'scale={width}:-2:flags=lanczos'
    if extra_vf:
        vf = extra_vf + ',' + vf
    cmd = ['ffmpeg', '-v', 'error', '-y', '-i', src]
    if max_seconds:
        cmd += ['-t', str(max_seconds)]
    cmd += ['-vf', vf, '-c:v', 'libx264', '-preset', 'slow', '-crf', str(crf),
            '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', dst]
    sh(cmd)
    poster = dst[:-4] + '.webp'
    with tempfile.TemporaryDirectory() as td:
        jpg = os.path.join(td, 'f.png')
        sh(['ffmpeg', '-v', 'error', '-y', '-i', dst, '-frames:v', '1', jpg])
        save_webp(Image.open(jpg), poster, quality=78)
    dur = float(sh(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', dst]).strip())
    return round(dur, 2)


def write_js(name, var, data):
    mkdir(JS)
    with open(os.path.join(JS, name), 'w') as fh:
        fh.write('// Auto-generated by tools/build_assets.py — do not edit by hand.\n')
        fh.write(f'window.{var} = ')
        json.dump(data, fh, indent=1, ensure_ascii=False)
        fh.write(';\n')


